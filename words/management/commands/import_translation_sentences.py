# 已人工核验参考译文的年份：核验后加入对应年份并重跑本命令
VERIFIED_YEARS = set()

# 按题号 (46)-(50) 拆句
SENT_RE = re.compile(r'\((4[6-9]|50)\)\s*(.*?)(?=\s*\((?:4[6-9]|50)\)|$)', re.S)


class Command(BaseCommand):
    help = '导入英语一翻译真题逐句数据（需先运行 import_exam_questions）'

    def handle(self, *args, **options):
        questions = ExamQuestion.objects.filter(
            exam_type='english1', question_type='translation')
        if not questions.exists():
            self.stdout.write(self.style.WARNING(
                '未找到英语一翻译真题，请先运行 python manage.py import_exam_questions'))
            return

        created = updated = skipped = 0
        for q in questions:
            matches = SENT_RE.findall(q.content or '')
            if not matches:
                skipped += 1
                self.stdout.write(self.style.WARNING(f'跳过（未拆出句子）：{q}'))
                continue
            zh_map = E1_TRANSLATION_ZH.get(q.year, {})
            tag_map = E1_SYNTAX_TAGS.get(q.year, {})
            diff_map = E1_DIFFICULTY.get(q.year, {})
            for num_str, en in matches:
                num = int(num_str)
                zh = zh_map.get(num, '').strip()
                notes = [f'考研英语一 {q.year} 年翻译真题第 {num} 题']
                if not zh:
                    notes.append('参考译文待补充')
                defaults = {
                    'sentence_en': ' '.join(en.split()),
                    'sentence_zh': zh,
                    'syntax_tags': tag_map.get(num, []),
                    'difficulty': diff_map.get(num, 3),
                    'source_type': 'past_paper',
                    'source_note': '；'.join(notes),
                    'verified': bool(zh) and q.year in VERIFIED_YEARS,
                }
                _, is_created = TranslationSentence.objects.update_or_create(
                    question=q, order=num - 45, defaults=defaults)
                if is_created:
                    created += 1
                else:
                    updated += 1

        total = TranslationSentence.objects.count()
        msg = f'导入完成：新增 {created} 条，更新 {updated} 条'
        if skipped:
            msg += f'，跳过 {skipped} 个年份'
        self.stdout.write(self.style.SUCCESS(msg))
        self.stdout.write(f'当前逐句真题总数：{total}')
        no_zh = TranslationSentence.objects.filter(sentence_zh='').count()
        if no_zh:
            self.stdout.write(self.style.WARNING(f'其中 {no_zh} 句缺参考译文'))
